import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

df = pd.read_csv("/content/Household_preprecessed.csv")

sns.lmplot(data=df, x="sqft_living", y="price", height=6)
plt.title("Living Area vs Price")
plt.show()

plt.figure(figsize=(7,5))
sns.boxplot(data=df, x="waterfront", y="price")
plt.title("Price by Waterfront Status")
plt.show()

plt.figure(figsize=(9,6))
plt.scatter(df["long"], df["lat"], c=df["price"],
            cmap="viridis", alpha=0.5)
plt.colorbar(label="Price")
plt.xlabel("Longitude")
plt.ylabel("Latitude")
plt.title("Geographic House Price Distribution")
plt.show()

top = df.groupby("zipcode")["price"].mean().sort_values(ascending=False).head(10)
print("Top High-Value Locations:")
print(top)

print("\nREAL ESTATE INVESTMENT SUMMARY")
print("Average Price:", round(df["price"].mean(), 2))
print("Highest Average Price ZIP:", top.index[0])
print("Highest Average ZIP Price:", round(top.iloc[0], 2))
print("Higher-grade and waterfront properties generally show higher prices.")
print("Geographic clusters with high prices can be considered premium investment locations.")