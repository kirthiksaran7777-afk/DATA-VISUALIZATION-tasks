df['date'] = pd.to_datetime(df['date'], errors='coerce')
df['Sale Year'] = df['date'].dt.year
df['Property Age'] = df['Sale Year'] - df['yr_built']
df['Is Renovated'] = (df['yr_renovated'] > 0).astype(int)
df['Years Since Renovation'] = (
    df['Sale Year'] - df['yr_renovated']
).where(df['yr_renovated'] > 0, 0)

print(df[['date', 'Sale Year', 'Property Age',
          'Is Renovated', 'Years Since Renovation']].head())

df['Price_per_Living_Sqft'] = df['price'] / df['sqft_living']
df['Price_per_Lot_Sqft'] = df['price'] / df['sqft_lot']

print(df[['price', 'sqft_living', 'sqft_lot',
          'Price_per_Living_Sqft',
          'Price_per_Lot_Sqft']].head())

import numpy as np

for c in ["bedrooms", "bathrooms"]:
    df[c] = df[c].replace(0, np.nan)
    df[c] = df[c].fillna(df.groupby("grade")[c].transform("median")).fillna(df[c].median())
df["bedrooms"] = df["bedrooms"].round().astype(int)
df = df.dropna(subset=["price", "sqft_living", "sqft_lot"])

df["date"] = pd.to_datetime(df["date"], format="%Y%m%dT%H%M%S")
df["sale_year"], df["sale_month"] = df["date"].dt.year, df["date"].dt.month
df["house_age"] = (df["sale_year"] - df["yr_built"]).clip(lower=0)
reno = df["yr_renovated"].replace(0, np.nan)
df["years_since_reno"] = df["sale_year"] - reno
df["effective_age"] = df["years_since_reno"].fillna(df["house_age"]).clip(lower=0)
df["is_renovated"] = reno.notna().astype(int)

df["price_per_sqft_living"] = df["price"] / df["sqft_living"]
df["price_per_sqft_lot"] = df["price"] / df["sqft_lot"]

cols = ["price", "price_per_sqft_living", "price_per_sqft_lot"]
fig, ax = plt.subplots(1, 3, figsize=(15, 4))
for a, c in zip(ax, cols):
    sns.boxplot(x=df[c], ax=a)
    a.set_title(c)
plt.show()

def fences(s, k=3):
    q1, q3 = s.quantile([.25, .75])
    return q1 - k * (q3 - q1), q3 + k * (q3 - q1)

lo, hi = fences(df["price"])
lo2, hi2 = fences(df["price_per_sqft_living"])
df["valuation_outlier"] = (~df["price"].between(lo, hi) |
                           ~df["price_per_sqft_living"].between(lo2, hi2)).astype(int)

print(df["valuation_outlier"].sum(), "extreme outliers")
df_clean = df[df["valuation_outlier"] == 0]